def _bullets(items: tuple[str, ...]) -> str:
    """Convert tuple of strings to Markdown bullet list, with heading support.

    Strings starting with '## ' become level-3 headings (### ...).
    Strings starting with '### ' become level-4 headings (#### ...).
    Strings starting with '  - ' are nested bullet items (preserved as-is).
    All other strings become bullet items (- ...).
    Avoids double blank lines between sections.
    """
    lines = []
    for item in items:
        if item.startswith("### "):
            lines.append(f"\n#### {item[4:]}")
        elif item.startswith("## "):
            lines.append(f"\n### {item[3:]}")
        elif item.startswith("  - "):
            lines.append(item)
        else:
            lines.append(f"- {item}")
    result = "\n".join(lines)
    while "\n\n\n" in result:
        result = result.replace("\n\n\n", "\n\n")
    return result


def language_policy_init_options(
    artifact_language: str = DEFAULT_ARTIFACT_LANGUAGE,
    product_locale: str = DEFAULT_PRODUCT_LOCALE,
) -> dict[str, str]:
    """Return machine-readable language policy defaults for init-options.json."""
    return {
        "artifact_language": artifact_language,
        "product_locale": product_locale,
    }


def _locale_label(locale: str) -> str:
    """Return a human-readable label for a product locale."""
    labels = {
        "es-CL": "Spanish — Chile",
        "es-ES": "Spanish — Spain",
    }
    return labels.get(locale, locale)


